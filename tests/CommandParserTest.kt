package com.sven.assistant

import java.time.*

fun main() {
    val z = ZoneId.of("UTC")
    val now = LocalDateTime.of(2026, 10, 26, 10, 0).atZone(z).toInstant().toEpochMilli()
    fun p(s: String) = CommandParser.parse(s, now, z)
    fun tool(s: String) = p(s)?.tool

    T.eq("open", "open_app", tool("open Maps"))
    T.eq("open compound rejected", null, tool("open maps and search for pizza"))
    T.eq("alarm 7:30 am", "alarm:7:30", p("set alarm for 7:30 am")?.expect)
    T.eq("alarm 6pm", "alarm:18:0", p("set an alarm at 6 pm called gym")?.expect)
    T.eq("alarm label", "gym", p("set an alarm at 6 pm called gym")?.args?.getString("label"))
    val rep = p("set alarm for 7 every weekday")
    T.eq("alarm weekdays days", "[2,3,4,5,6]", rep?.args?.getJSONArray("days")?.toString())
    T.eq("wake me", "set_alarm", tool("wake me up at 6:15"))
    T.eq("timer", "remind", tool("timer 5 minutes"))
    T.eq("timer kind", "timer", p("set a timer for 10 minutes")?.args?.getString("kind"))
    T.eq("timer when", now + 600_000, p("set a timer for 10 minutes")?.args?.getLong("when"))
    val r = p("remind me to call the dentist tomorrow at 9")!!
    T.eq("remind text", "call the dentist", r.args.getString("text"))
    T.eq("remind when", LocalDateTime.of(2026, 10, 27, 9, 0).atZone(z).toInstant().toEpochMilli(), r.args.getLong("when"))
    T.eq("remind in", "stretch", p("remind me in 20 minutes to stretch")?.args?.getString("text"))
    T.check("remind missing time", p("remind me to buy milk")?.args?.optBoolean("missingTime") == true)
    val rr = p("remind me to take vitamins every day at 8 am")!!
    T.eq("remind repeat", "DAILY", rr.args.getString("repeat")); T.eq("remind repeat text", "take vitamins", rr.args.getString("text"))
    T.eq("call number", "dial", tool("call 555-0100"))
    T.eq("call contact", "call_contact", tool("call mom"))
    T.eq("call contact name", "mom", p("call mom")?.args?.getString("name"))
    T.eq("call and ...", null, tool("call mom and text dad"))
    T.eq("text number", "compose_sms", tool("text 5550100 running late"))
    T.eq("text contact saying", "text_contact", tool("text John Smith saying I'm outside"))
    T.eq("text contact name", "John Smith", p("text John Smith saying I'm outside")?.args?.getString("name"))
    T.eq("text contact simple", "text_contact", tool("text mom hello there"))
    T.eq("email", "compose_email", tool("email bob@example.com about lunch"))
    T.eq("add event", "add_event", tool("add event dentist tomorrow at 3pm"))
    T.eq("add event title", "dentist", p("add event dentist tomorrow at 3pm")?.args?.getString("title"))
    T.eq("calendar", "read_calendar", tool("what's on my calendar"))
    T.eq("calendar tomorrow", "tomorrow", p("what do i have tomorrow")?.args?.getString("range"))
    T.eq("briefing", "briefing", tool("give me my briefing"))
    T.eq("battery", "battery", tool("what's my battery"))
    T.eq("media", "media_control", tool("pause the music"))
    T.eq("media next", "next", p("skip")?.args?.getString("action"))
    T.eq("play", "play_media", tool("play daft punk on spotify"))
    T.eq("settings wifi", "settings", tool("open wifi settings"))
    T.eq("settings page", "wifi", p("open wi-fi settings")?.args?.getString("page"))
    T.eq("flash on", "torch:on", p("turn on the flashlight")?.expect)
    T.eq("flash off", "torch:off", p("torch off")?.expect)
    T.eq("volume pct", "volume:40", p("set volume to 40%")?.expect)
    T.eq("search", "web_search", tool("search for best pizza"))
    T.eq("navigate", "navigate", tool("navigate to Central Park"))
    T.eq("go home", "system_nav", tool("go home"))
    T.eq("chat is not tool", null, tool("tell me a joke"))
    T.eq("question not tool", null, tool("what is the capital of France"))
    T.eq("goal wifi", "wifi:on", GoalExpectation.parse("turn on wifi"))
    T.eq("goal bt off", "bluetooth:off", GoalExpectation.parse("please turn the bluetooth off"))
    T.eq("goal airplane", "airplane:on", GoalExpectation.parse("enable airplane mode"))
    T.eq("goal none", null, GoalExpectation.parse("open instagram"))
    T.finish("CommandParserTest")
}
